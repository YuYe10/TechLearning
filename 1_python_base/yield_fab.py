#!/usr/bin/python3
 
from typing import Any, Generator


import sys
 
def fibonacci(n) -> Generator[int, Any, None]: # 生成器函数 - 斐波那契
    a, b, counter = 0, 1, 0
    while True:
        if (counter > n):
            return
        yield a
        a, b = b, a + b
        counter += 1
f: Generator[int, Any, None] = fibonacci(n=10) # f 是一个迭代器，由生成器返回生成
 
while True:
    try:
        print (next(f), end=" ")
    except StopIteration:
        sys.exit()